import { readdirSync, writeFileSync, existsSync } from "fs";
import { join, basename } from "path";
import { fileURLToPath } from "url";

const __dirname = fileURLToPath(new URL(".", import.meta.url));
const ICONS_DIR = join(__dirname, "..", "src", "assets", "icons");
const OUTPUT = join(__dirname, "..", "src", "lib", "icons", "generated.ts");

const styles = ["linear", "line-duotone", "bold", "bold-duotone", "broken", "outline"];
const iconNames = new Set();

for (const style of styles) {
  const dir = join(ICONS_DIR, style);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir).filter((f) => f.endsWith(".svg"));
  for (const file of files) {
    iconNames.add(basename(file, ".svg"));
  }
}

const sorted = [...iconNames].sort();
const iconNameType = sorted.map((n) => `  | "${n}"`).join("\n");

const content = `// Auto-generated by scripts/generate-icon-types.mjs
// Do not edit manually. Run: npm run icons:generate-types

export type GeneratedIconName =
${iconNameType};

export const AVAILABLE_ICONS: string[] = [
${sorted.map((n) => `  "${n}",`).join("\n")}
];
`;

writeFileSync(OUTPUT, content, "utf-8");
console.log(`Generated ${sorted.length} icon names → lib/icons/generated.ts`);
